import * as canvasText from '../generate/canvas-text';
import { Hono } from 'hono';
import { mountJson } from '../../core/handler';
import * as imageGen from '../generate/image';
import * as videoGen from '../generate/video';
import * as depthVideo from '../generate/depth-video';
import * as depthImage from '../generate/depth-image';
import * as analyze from '../generate/analyze';
import * as copywriting from '../generate/copywriting';
import * as headlineTitle from '../generate/headline-title';
import * as headlineDesign from '../generate/headline-design';
import * as exportZip from '../generate/export-zip';
import * as uploadRef from '../generate/upload-ref';
import * as layerDecomposition from '../generate/layer-decomposition';
import * as keywordReview from '../generate/keyword-review';

const generate = new Hono();
generate.post('/canvas-text', mountJson((req) => canvasText.POST(req)));

generate.post('/layer-decomposition', mountJson((req) => layerDecomposition.POST(req)));
generate.post('/keyword-review/balance', mountJson((req) => keywordReview.balancePOST(req)));
generate.get('/keyword-review/rules', mountJson(() => keywordReview.rulesGET()));
generate.put('/keyword-review/rules', mountJson((req) => keywordReview.rulesPUT(req)));
generate.post('/keyword-review', mountJson((req) => keywordReview.POST(req)));
generate.post('/image', mountJson((req) => imageGen.POST(req)));
generate.get('/image', mountJson((req) => imageGen.GET(req)));
generate.post('/video', mountJson((req) => videoGen.POST(req)));
generate.get('/video', mountJson((req) => videoGen.GET(req)));
generate.post('/depth-video', mountJson((req) => depthVideo.POST(req)));
generate.get('/depth-video', mountJson((req) => depthVideo.GET(req)));
generate.post('/depth-image', mountJson((req) => depthImage.POST(req)));
generate.get('/depth-image', mountJson((req) => depthImage.GET(req)));
generate.post('/analyze', mountJson((req) => analyze.POST(req)));
generate.post('/copywriting', mountJson((req) => copywriting.POST(req)));
generate.post('/headline-title', mountJson((req) => headlineTitle.POST(req)));
generate.post('/headline-design', mountJson((req) => headlineDesign.POST(req)));
generate.post('/export-zip', mountJson((req) => exportZip.POST(req)));
generate.post('/upload-ref', mountJson((req) => uploadRef.POST(req)));

export default generate;
