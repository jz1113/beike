export interface CoverSkillSection {
  heading: string;
  body: string[];
}

export interface CoverSkill {
  id: 'generate' | 'deconstruct';
  title: string;
  summary: string;
  appliesWhen: string;
  input: string;
  output: string;
  flow: string[];
  sections: CoverSkillSection[];
}

export function coverSkillMemoryStatus(adoptedCount: number, pendingCount: number): { summary: string; note: string } {
  return {
    summary: `已采纳 ${adoptedCount} 条 · 待确认 ${pendingCount} 条`,
    note: '待确认不会参与生成。采纳与纠正自动保存经验版本；生成引用全局纠正和一张样张，反馈帮助选样。',
  };
}

