func fashionCameraRules() string {
	return `服饰运镜默认固定手机机位，或保持相同拍摄距离的小幅横移、轻微跟拍；禁止默认推近、变焦、数码裁切放大、快速贴近商品或停留拍摄 logo。镜头和人物都保持正常展示距离，不通过人物靠近镜头变成近景。
靠姿态、手势和站位变化展示版型、垂坠与搭配，剪切也保持中景、中全景或全身，不用细节插镜突出模糊的标志。说话段在中景保持嘴部可见并同步口型，背面或全身展示放在停顿或画外音段。
旧分镜中的近景、特写或推近在重新定稿时改为正常距离的展示动作，不改变台词、声音来源与起止秒数。若实际参考素材只支持局部，说明需要补充中景素材，不虚构画外的服装结构，也不声称已修复模糊 logo。` + "\n" + fashionPerformanceRules()
}

func fashionPerformanceRules() string {
	return `实拍表演与连续性：默认固定手机机位，背景墙线和家具位置稳定；画面变化来自有目的的展示，不为生活感添加周期晃动、自动失焦、曝光跳变、噪点或伪造设备参数。
每段围绕一个可见事实安排一个主要动作，写明起始姿态、接触部位、动作结果与收势；例如捏住侧边衣摆轻轻拉开，再松手回落。只展示有依据的结构，不把拉扯当弹性证明，不凭图推断柔软或舒适。手先接触再带动衣料，接触处产生局部褶皱，松手后按材质和重力回落；脚先承重再换重心，衣摆、袖口和头发随身体动作滞后后收住，不独立飘动、不穿模、不脚滑。
说话时可做嘴部无遮挡、无需大幅低头的轻手势，不让人物说完每句都僵住；句间再安排侧身或重心变化。表情和视线随语义变化，不持续微笑、节拍式点头或左右循环摆动；眨眼、呼吸不逐秒编排。
分镜是语义时间段，不等于必须切镜或换参考图。短片优先同场景连续展示，按信息需要硬切，动作有起落，不平均分配镜头；不把长参考片的换装、多套搭配和所有手势压进短片。换装只能在明确剪辑点发生，不在连续帧里让衣服变形换色。`
}

