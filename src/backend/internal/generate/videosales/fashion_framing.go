func fashionStillFramingRules() string {
	return `服饰构图默认以中景、中全景和全身展示为主，保留整件商品的轮廓、穿搭比例和周围空间；不默认安排近景、特写、微距或局部占满画面。
出镜讲解用头顶至腰部或大腿的正面或轻微侧面中景，完整头部、嘴唇和主要服装同时入画，嘴部无遮挡，保持自然比例，不为对口型裁成脸部、嘴部或胸前局部大画面。真实肤质自然呈现，不为展示毛孔放大脸部。
展示结构或面料时，在正常距离内轻抬手、整理衣摆、侧身或展示整件商品，不把商品、鞋包或胸前标志举到镜头前。鞋包保留整件和上脚或手持关系。logo、文字、刺绣和小五金保持原图中的位置与自然比例，不作为画面主体，不要求逐字清晰可读，不编造、补字、改写、删除或用人为模糊遮盖错误。
人脸参考仅用于继承身份，不意味着成片要复刻脸部特写；商品原图中的局部图只作为事实对照，不直接沿用其裁切作为主画面。讲解人物和商品关键帧须能支撑中景展示。`
}

func fashionCameraRules() string {
	return `服饰运镜默认固定手机机位，或保持相同拍摄距离的小幅横移、轻微跟拍；禁止默认推近、变焦、数码裁切放大、快速贴近商品或停留拍摄 logo。镜头和人物都保持正常展示距离，不通过人物靠近镜头变成近景。
靠姿态、手势和站位变化展示版型、垂坠与搭配，剪切也保持中景、中全景或全身，不用细节插镜突出模糊的标志。说话段在中景保持嘴部可见并同步口型，背面或全身展示放在停顿或画外音段。
旧分镜中的近景、特写或推近在重新定稿时改为正常距离的展示动作，不改变台词、声音来源与起止秒数。若实际参考素材只支持局部，说明需要补充中景素材，不虚构画外的服装结构，也不声称已修复模糊 logo。`
}

func fashionFramingRules() string {
	return fashionStillFramingRules() + "\n" + fashionCameraRules()
}
