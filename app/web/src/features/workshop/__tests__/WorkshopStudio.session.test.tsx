import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, render, screen, fireEvent } from '@testing-library/react';
import { useAppStore } from '@/store/useAppStore';
import WorkshopStudio from '../WorkshopStudio';
vi.mock('../batch/BatchWorkshopView', () => ({ default: () => <input aria-label="批量草稿" defaultValue="初始" /> }));
vi.mock('../components/WorkshopTopBar', () => ({ WorkshopTopBar: () => null }));
vi.mock('../components/WorkshopSideCapsuleBar', () => ({ WorkshopSideCapsuleBar: () => null }));
vi.mock('../views/WorkshopRecipeView', () => ({ default: () => null }));
vi.mock('../views/WorkshopProductView', () => ({ default: () => null }));
vi.mock('@/features/assets/AssetPromptLibrary', () => ({ default: () => <div>资产库</div> }));
afterEach(cleanup);
it('keeps the same batch component alive while visiting the prompt library', () => {
  useAppStore.setState({ activeWorkshopTab: 'studio' });
  const { rerender } = render(<WorkshopStudio />);
  const original = screen.getByLabelText('批量草稿') as HTMLInputElement;
  fireEvent.change(original, { target: { value: '已经编辑的商品和分镜' } });
  useAppStore.setState({ activeWorkshopTab: 'prompt_assets' }); rerender(<WorkshopStudio />);
  expect(screen.getByText('资产库')).toBeTruthy();
  useAppStore.setState({ activeWorkshopTab: 'studio' }); rerender(<WorkshopStudio />);
  expect(screen.getByLabelText('批量草稿')).toBe(original);
  expect(original.value).toBe('已经编辑的商品和分镜');
});
