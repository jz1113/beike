import {afterEach,expect,it,vi} from 'vitest';
vi.mock('@/lib/apiClient',()=>({apiFetch:vi.fn(),proxyMediaUrl:(url:string)=>url}));
vi.mock('../canvasMediaImport',()=>({persistCanvasMedia:vi.fn()}));
import {apiFetch} from '@/lib/apiClient';
import {persistCanvasMedia} from '../canvasMediaImport';
import {layerBounds,mergeCanvasLayers,orderedLayers} from '../canvasLayers';
import type {CanvasNode} from '../types';
const layer=(id:string,order:number,patch:Partial<CanvasNode>={}):CanvasNode=>({id,layerOrder:order,type:'image',imageUrl:`https://example.com/${id}.png`,x:10,y:20,width:100,height:200,createdAt:1,...patch});
afterEach(()=>{vi.restoreAllMocks();vi.unstubAllGlobals();vi.clearAllMocks();});
it('merges visible layers in paint order with correct offsets and opacity, retaining originals',async()=>{
 const nodes=[layer('top',2,{x:60,layerOpacity:0.5}),layer('hidden',1,{layerHidden:true}),layer('base',0)];
 const snapshot=JSON.stringify(nodes);
 const context={globalAlpha:1,drawImage:vi.fn()};
 const alphas:number[]=[];context.drawImage.mockImplementation(()=>{alphas.push(context.globalAlpha);});
 vi.spyOn(HTMLCanvasElement.prototype,'getContext').mockReturnValue(context as unknown as CanvasRenderingContext2D);
 vi.spyOn(HTMLCanvasElement.prototype,'toBlob').mockImplementation(callback=>callback(new Blob(['png'],{type:'image/png'})));
 const close=vi.fn();vi.stubGlobal('createImageBitmap',vi.fn(async()=>({width:200,height:400,close})));
 vi.mocked(apiFetch).mockImplementation(async()=>new Response(new Blob(['image'])));
 vi.mocked(persistCanvasMedia).mockResolvedValue({type:'image',imageUrl:'/saved.png',x:0,y:0,width:300,height:400});
 const result=await mergeCanvasLayers(nodes);
 expect(vi.mocked(apiFetch).mock.calls.map(call=>call[0])).toEqual(['https://example.com/base.png','https://example.com/top.png']);
 expect(alphas).toEqual([1,0.5]);
 expect(context.drawImage.mock.calls[1].slice(1)).toEqual([100,0,200,400]);
 expect(result).toMatchObject({imageUrl:'/saved.png',x:220,y:20,width:150,height:200});
 expect(close).toHaveBeenCalledTimes(2);expect(JSON.stringify(nodes)).toBe(snapshot);
});
it('rejects empty or invalid compositions without uploading',async()=>{
 await expect(mergeCanvasLayers([layer('hidden',0,{layerHidden:true})])).rejects.toThrow('至少');
 expect(()=>layerBounds([layer('bad',0,{width:NaN})])).toThrow('尺寸');
 expect(persistCanvasMedia).not.toHaveBeenCalled();
 expect(orderedLayers([layer('top',3),layer('base',0)]).map(n=>n.id)).toEqual(['base','top']);
});
