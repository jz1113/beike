import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
vi.mock('@/lib/credentialClient', () => ({ credentialGet: vi.fn(async () => 'secret'), credentialSet: vi.fn(async () => {}) }));
const requests = vi.hoisted(() => ({ fetch: vi.fn() }));
vi.mock('@/lib/apiClient', () => ({ apiFetch: requests.fetch }));
import { ImageGatewayPanel } from './ImageGatewayPanel';
afterEach(() => { cleanup(); localStorage.clear(); vi.clearAllMocks(); });
it('saves only checked image models and restores the selection on reopening', async () => {
  localStorage.setItem('image_gateway_enabled', 'true');
  localStorage.setItem('image_base_url', 'https://images.example.com');
  const models = [{ id: 'independent-model', isImage: true }, { id: 'comfly-model', isImage: true }, { id: 'video-only', isImage: false, isVideo: true }];
  const { unmount } = render(<ImageGatewayPanel models={models} />);
  const save = screen.getByRole('button', { name: '保存独立网关配置' });
  await waitFor(() => expect((save as HTMLButtonElement).disabled).toBe(false));
  fireEvent.click(screen.getByRole('checkbox', { name: /comfly-model/ }));
  fireEvent.click(save);
  await waitFor(() => expect(JSON.parse(localStorage.getItem('image_gateway_models') || 'null')).toEqual(['independent-model']));
  expect(screen.queryByText(/video-only/)).toBeNull();
  unmount();
  render(<ImageGatewayPanel models={models} />);
  await waitFor(() => expect(screen.getByText('comfly-model · Comfly')).toBeTruthy());
  expect((screen.getByRole('checkbox', { name: /comfly-model/ }) as HTMLInputElement).checked).toBe(false);
});

it('pulls its own catalog and saves a text model without duplicating an existing model ID', async () => {
  localStorage.setItem('image_gateway_enabled', 'true');
  localStorage.setItem('image_base_url', 'https://second.example.com/endpoint');
  localStorage.setItem('custom_models', JSON.stringify([{ id: 'gpt-5.6-luna', isImage: false }]));
  requests.fetch.mockResolvedValue(Response.json({ success: true, models: [{ id: 'gpt-5.6-luna', name: 'Luna' }] }));
  render(<ImageGatewayPanel models={[{ id: 'gpt-5.6-luna', isImage: false }]} />);
  const pull = screen.getByRole('button', { name: '拉取独立网关模型' });
  await waitFor(() => expect((pull as HTMLButtonElement).disabled).toBe(false));
  fireEvent.click(pull);
  fireEvent.click(await screen.findByRole('button', { name: '使用独立网关' }));
  fireEvent.click(screen.getByRole('button', { name: '保存独立网关配置' }));
  await waitFor(() => expect(JSON.parse(localStorage.getItem('independent_text_models') || '[]')).toEqual(['gpt-5.6-luna']));
  expect(JSON.parse(localStorage.getItem('custom_models') || '[]')).toHaveLength(1);
  const body = JSON.parse(requests.fetch.mock.calls[0][1].body);
  expect(body).toEqual({ strict: true, baseUrl: 'https://second.example.com/endpoint', apiKey: 'secret' });
});
it('does not offer fallback models as independent gateway discoveries', async () => {
  localStorage.setItem('image_base_url', 'https://second.example.com');
  requests.fetch.mockResolvedValue(Response.json({ success: true, isFallback: true, models: [{ id: 'fake-model' }] }));
  render(<ImageGatewayPanel models={[]} />);
  const pull = screen.getByRole('button', { name: '拉取独立网关模型' });
  await waitFor(() => expect((pull as HTMLButtonElement).disabled).toBe(false));
  fireEvent.click(pull);
  await screen.findByText('网关未返回真实模型列表');
  expect(screen.queryByText(/fake-model/)).toBeNull();
});
