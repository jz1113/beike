export function migrateTravelCopySkill(skill: AssistantSkill): AssistantSkill {
  if (skill.isBuiltin || skill.id !== 'meituan-xhs-travel-copy' ||
      !skill.prompt?.includes('暂不生成正式文案') ||
      !skill.prompt.includes('必须有目的地及其对应的文化体验素材')) return skill;
  const rewrite = (text: string) => replacements.reduce((value, [before, after]) => value.replaceAll(before, after), text);
  return { ...skill, prompt: rewrite(skill.prompt),
    description: rewrite(skill.description || ''),
    ...(skill.markdownDoc ? { markdownDoc: rewrite(skill.markdownDoc) } : {}),
    updatedAt: Date.now() };
}
